@unittest.skipUnless(os.environ.get("RUN_PW_CORE_INTEGRATION_TEST") == "1",
                      "Live integration check - spawns a real Chromium and drives the repo's own "
                      "mock EMS app (app/test_server.py, run separately: python -m app.test_server). "
                      "Set RUN_PW_CORE_INTEGRATION_TEST=1 to run.")
class TestPlaywrightCoreLiveIntegration(unittest.TestCase):
    """Proves the Playwright Core fallback engine really drives a browser end to end: a real
    button click on the mock EMS app must produce OBSERVED_BEHAVIOR with
    execution_engine == PLAYWRIGHT_CORE - not a mocked/simulated result."""

    def test_real_button_click_produces_observed_behavior(self):
        import asyncio
        import tempfile
        from playwright.async_api import async_playwright
        from app.playwright_core_engine import run_playwright_core_exploration

        base_url = os.environ.get("PW_CORE_INTEGRATION_TARGET_URL", "http://127.0.0.1:8080")
        target_url = f"{base_url}/dashboard"

        async def login_and_export_storage_state(path):
            # Mirrors what crawler.py does after a successful login: export cookies so the
            # fallback engine's browser starts already authenticated, exactly like the real
            # pipeline (requirement: reuse the crawler's authenticated storage state).
            async with async_playwright() as p:
                browser = await p.chromium.launch(headless=True, args=["--no-sandbox"])
                context = await browser.new_context()
                page = await context.new_page()
                await page.goto(f"{base_url}/login", wait_until="load", timeout=20000)
                await page.fill("#username", "admin")
                await page.fill("#password", "admin123")
                await page.click("button[type='submit']")
                await page.wait_for_load_state("networkidle", timeout=10000)
                await context.storage_state(path=path)
                await browser.close()

        with tempfile.NamedTemporaryFile(suffix=".json", delete=False) as tmp:
            storage_state_path = tmp.name
        asyncio.run(login_and_export_storage_state(storage_state_path))

        scope_ctx = ScopeContext(
            scan_scope="MODULE", parent_module="General", selected_module="Dashboard",
            target_urls=[target_url], allowed_features=[]
        )
        feature_queue = [{
            "module": "Module - EMS Dashboard", "page": "EMS Dashboard", "feature": "Button Click Edit",
            "url": target_url, "feature_type": "Action", "locator_hint": 'text="Edit"', "fields": []
        }]
        discovered_modules = {}

        metrics = asyncio.run(run_playwright_core_exploration(
            "test_scan_pwcore_live", base_url, feature_queue, storage_state_path, scope_ctx, discovered_modules
        ))

        self.assertGreater(metrics["pw_core_successful_calls"], 0)
        feat = discovered_modules["Module - EMS Dashboard"].features[0]
        self.assertEqual(feat.source_classification, "OBSERVED_BEHAVIOR")
        self.assertEqual(feat.execution_engine, "PLAYWRIGHT_CORE")
        self.assertTrue(feat.is_observed)


