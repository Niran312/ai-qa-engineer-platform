class TestPlaywrightCoreEngine(unittest.TestCase):
    """Exercises run_playwright_core_exploration() directly (the fallback engine's own
    dispatch/safety-gate logic), with Playwright itself faked out so no real browser is needed."""

    class _FakeKeyboard:
        async def press(self, key):
            pass

    class _FakeLocator:
        def __init__(self, page, selector):
            self._page = page
            self._selector = selector

        @property
        def first(self):
            return self

        async def click(self, timeout=None):
            self._page.clicked.append(self._selector)

        async def fill(self, value, timeout=None):
            self._page.filled.append((self._selector, value))

        async def check(self, timeout=None):
            self._page.checked.append(self._selector)

        async def select_option(self, index=None, timeout=None):
            self._page.checked.append(self._selector)

    class _FakePage:
        def __init__(self):
            self.url = "http://example.com/client-management/clients/"
            self.clicked = []
            self.filled = []
            self.checked = []
            self.keyboard = TestPlaywrightCoreEngine._FakeKeyboard()

        async def goto(self, url, wait_until=None, timeout=None):
            self.url = url

        def locator(self, selector):
            return TestPlaywrightCoreEngine._FakeLocator(self, selector)

        async def wait_for_timeout(self, ms):
            pass

        async def title(self):
            return "Clients"

        async def evaluate(self, script):
            return {}

    def _make_fake_async_playwright(self, page):
        class _FakeBrowser:
            async def new_context(self, **kwargs):
                return _FakeContext()

            async def close(self):
                pass

        class _FakeContext:
            async def new_page(self):
                return page

            async def close(self):
                pass

        class _FakeChromium:
            async def launch(self, **kwargs):
                return _FakeBrowser()

        class _FakeP:
            chromium = _FakeChromium()

        class _FakeAsyncPlaywright:
            async def __aenter__(self):
                return _FakeP()

            async def __aexit__(self, *a):
                pass

        return lambda: _FakeAsyncPlaywright()

    def _run(self, feature_queue, page=None):
        import asyncio
        from app.playwright_core_engine import run_playwright_core_exploration
        page = page or self._FakePage()
        discovered_modules = {}
        scope_ctx = ScopeContext(
            scan_scope="MODULE", parent_module="Manage", selected_module="Clients",
            target_urls=["http://example.com/client-management/clients/"], allowed_features=[]
        )
        with unittest.mock.patch('app.playwright_core_engine.async_playwright', self._make_fake_async_playwright(page)):
            metrics = asyncio.run(run_playwright_core_exploration(
                "test_scan_pwcore", "http://example.com/", feature_queue, None, scope_ctx, discovered_modules
            ))
        return metrics, discovered_modules, page

    def test_safe_action_produces_observed_behavior(self):
        """A real, verified Playwright interaction -> OBSERVED_BEHAVIOR + execution_engine PLAYWRIGHT_CORE,
        and the button actually gets clicked."""
        feature_queue = [{
            "module": "Module - Clients", "page": "Clients", "feature": "Button Click Add Client",
            "url": "http://example.com/client-management/clients/", "feature_type": "Action",
            "locator_hint": "#_btnAdd", "fields": []
        }]
        metrics, discovered_modules, page = self._run(feature_queue)
        self.assertIn("#_btnAdd", page.clicked)
        self.assertGreater(metrics["pw_core_successful_calls"], 0)
        feat = discovered_modules["Module - Clients"].features[0]
        self.assertEqual(feat.source_classification, "OBSERVED_BEHAVIOR")
        self.assertEqual(feat.execution_engine, "PLAYWRIGHT_CORE")

    def test_destructive_action_is_skipped_not_clicked(self):
        """Safety Gateway applies equally to the fallback engine: a Delete action must be
        blocked exactly like it would be for MCP - SKIPPED_SCENARIO, never actually clicked."""
        feature_queue = [{
            "module": "Module - Clients", "page": "Clients", "feature": "Button Click Delete Client",
            "url": "http://example.com/client-management/clients/", "feature_type": "Action",
            "locator_hint": "text=\"Delete Client\"", "fields": []
        }]
        metrics, discovered_modules, page = self._run(feature_queue)
        self.assertEqual(page.clicked, [])
        feat = discovered_modules["Module - Clients"].features[0]
        self.assertEqual(feat.source_classification, "SKIPPED_SCENARIO")
        self.assertEqual(feat.execution_engine, "PLAYWRIGHT_CORE")
        self.assertFalse(feat.is_observed)

    def test_scope_confined_to_provided_queue_no_root_exploration(self):
        """The fallback engine only ever navigates to URLs present in the feature_queue it was
        handed (already MODULE-scope-filtered upstream) - it must never introduce or wander to
        any other URL, i.e. no root/public exploration."""
        target_url = "http://example.com/client-management/clients/"
        feature_queue = [
            {"module": "Module - Clients", "page": "Clients", "feature": "Explore main view",
             "url": target_url, "feature_type": "Read", "locator_hint": None, "fields": []},
            {"module": "Module - Clients", "page": "Clients", "feature": "Button Click Add Client",
             "url": target_url, "feature_type": "Action", "locator_hint": "#_btnAdd", "fields": []},
        ]
        page = self._FakePage()
        visited_urls = []
        original_goto = page.goto

        async def tracking_goto(url, **kwargs):
            visited_urls.append(url)
            await original_goto(url, **kwargs)
        page.goto = tracking_goto

        self._run(feature_queue, page=page)
        self.assertTrue(all(u == target_url for u in visited_urls))

class TestGenerateTestCasesAgainstRealScanData(unittest.TestCase):
    """Regression test for the 'name scan_scope is not defined' crash: replays the real
    app_map from a scan that hit it (stored in qa_platform.db) through generate_test_cases()
    with the LLM stages mocked out, and proves Stage 1 completes and output stays scoped to
    the requested module instead of crashing into the mock-generator fallback."""

    SCAN_ID = "9c88f309-1cc5-4209-bb05-d6863eaa1ccb"

    def setUp(self):
        db_path = os.path.join(settings.BASE_DIR, "qa_platform.db")
        if not os.path.exists(db_path):
            self.skipTest("qa_platform.db not present in this environment")
        conn = sqlite3.connect(db_path)
        conn.row_factory = sqlite3.Row
        cur = conn.cursor()
        cur.execute("SELECT app_map FROM scans WHERE id = ?", (self.SCAN_ID,))
        row = cur.fetchone()
        conn.close()
        if not row:
            self.skipTest(f"scan {self.SCAN_ID} not present in this environment")
        self.app_map = json.loads(row["app_map"])

    @staticmethod
    def _fake_query_llm(model, prompt, scan_id, stage_name):
        if stage_name.startswith("STAGE 1"):
            return json.dumps({
                "application_map": {"modules": []},
                "module_inventory": [{
                    "module_name": "Manage - Clients",
                    "features": ["Button Click Add Client", "Form Submit "],
                    "fields": [], "states": [], "dependencies": []
                }]
            })
        if stage_name.startswith("STAGE 2"):
            return json.dumps([
                {"feature_name": "Button Click Add Client",
                 "scenarios": ["Verify clicking Add Client opens the create-client form"]},
            ])
        if stage_name.startswith("STAGE 3"):
            return json.dumps([])
        if stage_name.startswith("STAGE 4") or stage_name.startswith("STAGE 5"):
            f_name = stage_name.split(" - ", 1)[-1] if " - " in stage_name else "Add Client"
            return json.dumps([{
                "module": "Manage - Clients",
                "submodule": "Clients",
                "page": "Clients",
                "feature": f_name,
                "scenario": f"Verify {f_name} behaves as observed",
                "test_type": "Functional",
                "priority": "Medium",
                "observed_behavior": "STRUCTURAL_EVIDENCE",
                "source_classification": "STRUCTURAL_EVIDENCE"
            }])
        raise AssertionError(f"Unexpected LLM stage invoked in offline test: {stage_name}")

    def test_generate_test_cases_completes_without_crashing(self):
        scope_ctx = ScopeContext(
            scan_scope="module",
            parent_module="Manage",
            selected_module="Clients",
            target_urls=["http://0.0.0.0/client-management/clients/"],
            allowed_features=["Manage -> Clients"]
        )
        empty_mcp_behavior = json.dumps({"modules": [], "safety_actions_log": [], "coverage_gaps": [], "metrics": {"mcp_actions_count": 0}})

        with unittest.mock.patch("app.generator.query_llm", side_effect=self._fake_query_llm), \
             unittest.mock.patch("app.generator.run_quality_gate", side_effect=lambda model, test_cases, scan_id, scope_ctx=None: test_cases):
            result = generate_test_cases(
                scan_id="offline-verify",
                app_map=self.app_map,
                user_description="",
                api_key="offline-test-key",
                mcp_behavior=empty_mcp_behavior,
                scope_ctx=scope_ctx
            )

        self.assertTrue(len(result) > 0)
        for tc in result:
            self.assertEqual(tc["module"], "Manage")
            self.assertEqual(tc["submodule"], "Clients")


